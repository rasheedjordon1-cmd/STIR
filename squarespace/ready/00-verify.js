/* STIR — preflight. Paste into the browser console (anywhere) BEFORE
   pasting anything into Squarespace, and again on the published site.

   GENERATED by scripts/build-squarespace.py for one specific build. It
   replaces an earlier check that only asked whether the stylesheet URL
   returned 200. It did return 200 — and returned the pre-rewrite
   stylesheet, which contains none of the classes this markup is built
   from. A reachability check cannot answer "is this the right one", so
   this one asks for the build by name. */
(async () => {
  const BASE  = 'https://stirnyc.netlify.app/assets/';
  const SHEET = 'stir-squarespace.26e3f464e6.css';
  const MUST  = ["scene/room-desk.webp", "scene/room-phone.webp", "scene/seat-desk.webp", "scene/seat-phone.webp", "scene/hero-desk-poster.webp", "scene/hero-phone-poster.webp", "stir-mark-cobalt.png"];
  const tag = (ok, m) => console.log('%c' + (ok ? 'PASS' : 'FAIL') + '%c  ' + m,
    'color:#fff;background:' + (ok ? '#1a7f37' : '#C4120D') +
    ';padding:1px 6px;border-radius:3px;font-weight:600', '');
  let bad = 0;
  const check = async (url, label) => {
    try {
      const r = await fetch(url, { cache: 'no-store' });
      if (!r.ok) { bad++; tag(false, label + '  — HTTP ' + r.status); return null; }
      tag(true, label); return r;
    } catch (e) { bad++; tag(false, label + '  — ' + e.message); return null; }
  };

  const r = await check(BASE + SHEET, 'stylesheet for THIS build (' + SHEET + ')');
  if (r) {
    /* Belt and braces: the name says which build, this says the file
       behind it is really the package and not an error page. */
    const css = await r.text();
    const sig = ['.scene-pair', '.action-label', '.ways', '.evidence'];
    const missing = sig.filter((c) => !css.includes(c));
    if (missing.length) { bad++; tag(false, 'stylesheet is missing ' + missing.join(', ')); }
    else tag(true, 'stylesheet carries the signature classes');
  }
  for (const f of MUST) await check(BASE + f, f);

  console.log('%c' + (bad
    ? bad + ' problem(s). Do not paste yet — the pages will render ' +
      'against the wrong CSS. Point Netlify’s production branch at the ' +
      'branch carrying this work and deploy, then run this again.'
    : 'All current. Safe to paste.'),
    'font-weight:600;font-size:13px;color:' + (bad ? '#C4120D' : '#1a7f37'));
})();
